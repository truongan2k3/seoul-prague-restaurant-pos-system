/** Encode UTF-8 string to Windows-1250 bytes for Czech thermal printers. */
export function encodeWindows1250(text: string): Uint8Array {
  const bytes: number[] = [];
  for (const ch of text) {
    const code = ch.charCodeAt(0);
    if (code < 128) {
      bytes.push(code);
      continue;
    }
    bytes.push(UNICODE_TO_WIN1250.get(code) ?? 0x3f);
  }
  return new Uint8Array(bytes);
}
